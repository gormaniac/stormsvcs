class FakeMalpedia:
    """A fake Malpedia API on localhost."""

    def __init__(self):
        self.state = initialState()
        self.requests: list[str] = []
        self.headers: list[dict] = []
        self.runner = None
        self.url = None

    def bibText(self, keys=None) -> str:
        """The bib entries, optionally only those with the given keys."""
        out = []
        for entry in self.state["bib"]:
            if keys is None or entry[1] in keys:
                out.append(bibEntry(*entry))
        return "\n".join(out)

    def yaraZip(self, tlp: str) -> bytes:
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as zfd:
            for filename, (_, text) in self.state["yara"].get(tlp, {}).items():
                zfd.writestr(filename, text)
        return buf.getvalue()

    def yaraList(self) -> dict:
        out = {}
        for tlp, files in self.state["yara"].items():
            for filename, (family, _) in files.items():
                out.setdefault(family, []).append({"path": f"/{family}/yara/{tlp}/{filename}", "tlp": tlp})
        return out

    def yaraFor(self, family: str) -> dict:
        out = {}
        for tlp, files in self.state["yara"].items():
            for filename, (fam, text) in files.items():
                if fam == family:
                    out.setdefault(tlp, {})[filename] = text
        return out

    def countPaths(self, prefix: str) -> int:
        """How many requests went to paths starting with prefix."""
        return sum(1 for path in self.requests if path.startswith(prefix))

    async def handle(self, request: web.Request) -> web.StreamResponse:
        path = request.path
        # The raw (still quoted) path, to check what the client actually sent.
        self.requests.append(request.raw_path)
        self.headers.append(dict(request.headers))

        errs = self.state["errors"].get(path)
        if errs:
            code = errs.pop(0)
            headers = {}
            # (code, Retry-After) tuples send a Retry-After header.
            if isinstance(code, tuple):
                code, headers["Retry-After"] = code
            return web.json_response({"detail": f"fake error {code}"}, status=code, headers=headers)

        state = self.state
        parts = path.strip("/").split("/")
        if parts[:1] != ["api"]:
            return web.json_response({"detail": "Not found."}, status=404)
        parts = parts[1:]

        def js(data):
            return web.json_response(copy.deepcopy(data))

        match parts:
            case ["get", "version"]:
                return js(state["version"])
            case ["list", "actors"]:
                return js(state["actorids"])
            case ["list", "families"]:
                return js(sorted(state["families"]))
            case ["get", "actors"]:
                return js(state["actors"])
            case ["get", "families"]:
                return js(state["families"])
            case ["get", "actor", aid]:
                if aid in state["actor"]:
                    return js(state["actor"][aid])
                for name, data in state["actors"].items():
                    if name.lower().replace(" ", "_").replace("/", "_") == aid:
                        data = copy.deepcopy(data)
                        data["families"] = {
                            fid: fam for fid, fam in state["families"].items()
                            if data["value"] in fam["attribution"]
                        }
                        return js(data)
                return web.json_response({"detail": "Not found."}, status=404)
            case ["get", "family", fid]:
                if fid in state["families"]:
                    return js(state["families"][fid])
                return web.json_response({"detail": "Not found."}, status=404)
            case ["get", "references"]:
                return js({"references": state["references"], "malpedia_version": state["version"]})
            case ["get", "bib"]:
                return web.Response(text=self.bibText(), content_type="text/plain")
            case ["get", "bib", "family", fid]:
                keys = state["families"].get(fid, {}).get("library_entries", [])
                return web.Response(text=self.bibText(keys), content_type="text/plain")
            case ["get", "bib", "actor", aid]:
                urls = {u for u, tags in state["references"].items() for t in tags if t["id"] == aid}
                keys = [e[1] for e in state["bib"] if e[6] in urls]
                return web.Response(text=self.bibText(keys), content_type="text/plain")
            case ["find", "actor", needle]:
                out = []
                for name, data in state["actors"].items():
                    syns = data["meta"].get("synonyms", [])
                    if any(needle.lower() in s.lower() for s in [name, *syns]):
                        out.append({"name": name.lower().replace(" ", "_").replace("/", "_"), "common_name": name, "synonyms": syns})
                return js(out)
            case ["find", "family", needle]:
                out = []
                for fid, fam in state["families"].items():
                    if any(needle.lower() in s.lower() for s in [fid, *fam["alt_names"]]):
                        out.append({"name": fid, "alt_names": fam["alt_names"]})
                return js(out)
            case ["list", "yara"]:
                return js(self.yaraList())
            case ["get", "yara", "after", _date]:
                out = {}
                for tlp, files in state["yara_after"].items():
                    for filename in files:
                        out.setdefault(tlp, {})[filename] = state["yara"][tlp][filename][1]
                return js(out)
            case ["get", "yara", tlp, "zip"]:
                return web.Response(body=self.yaraZip(tlp), content_type="application/zip")
            case ["get", "yara", fid]:
                return js(self.yaraFor(fid))
            case ["get", "misp"]:
                raise AssertionError("The service must never request /api/get/misp.")

        return web.json_response({"detail": "Not found."}, status=404)

    async def __aenter__(self):
        app = web.Application()
        app.router.add_route("GET", "/{tail:.*}", self.handle)
        self.runner = web.AppRunner(app)
        await self.runner.setup()
        site = web.TCPSite(self.runner, "127.0.0.1", 0)
        await site.start()
        port = site._server.sockets[0].getsockname()[1]
        self.url = f"http://127.0.0.1:{port}/api"
        return self

    async def __aexit__(self, *args):
        await self.runner.cleanup()


def svcConf(fake: FakeMalpedia, **kwargs) -> dict:
    """The service config for tests: fast, pointed at the fake, no autosync by default."""
    conf = {
        "malpedia:url": fake.url,
        "malpedia:interval": 0,
        "malpedia:backoff": 0,
        "malpedia:timeout": 30,
        "malpedia:pull:minage": 0,
        "malpedia:autosync": False,
    }
    conf.update(kwargs)
    return conf


@contextlib.asynccontextmanager
async def malpediaSvc(test, **conf):
    """Yield (core, svc, fake) - a Cortex with slib.malpedia added, pointed at a FakeMalpedia."""

    from malpediasvc import MalpediaSvc

    async with FakeMalpedia() as fake:
        sconf = svcConf(fake, **conf)
        async with test.getTestCoreProxSvc(MalpediaSvc, ssvc_conf=sconf) as (core, prox, svc):
            yield core, svc, fake


