def bibEntry(kind, key, author, title, date, org, url, orgfield="organization", lang="English"):
    """A BibTeX entry formatted exactly like Malpedia's."""
    return (
        f"@{kind}{{{key},\n"
        f"   author = {{{author}}},\n"
        f"   title = {{{{{title}}}}},\n"
        f"   date = {{{date}}},\n"
        f"   {orgfield} = {{{org}}},\n"
        f"   url = {{{url}}},\n"
        f"   language = {{{lang}}},\n"
        f"   urldate = {{2026-03-11}}\n"
        "}\n"
    )


